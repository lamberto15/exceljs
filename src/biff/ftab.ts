let names: string[] | undefined;
let fixed: Map<number, number> | undefined;

/** Function name for a table index ('' when unknown or macro-only). */
export function ftabName(i: number): string {
  if (names === undefined) {
    names = [];
    let at = 0;
    for (const t of NAMES.split(' ')) {
      if (t.charCodeAt(0) === 64) at = +t.slice(1);
      else names[at++] = t;
    }
  }
  return names[i] ?? '';
}

/** Argument count of a fixed-arity function, or -1 when unknown. */
export function ftabArgc(i: number): number {
  if (fixed === undefined) {
    fixed = new Map();
    for (const p of FIXED.split(' ')) {
      const c = p.indexOf(':');
      fixed.set(+p.slice(0, c), +p.slice(c + 1));
    }
  }
  return fixed.get(i) ?? -1;
}
