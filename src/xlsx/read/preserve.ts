// Round-trip capture (ReadOptions.preserveUnknown, default true): collects package parts, XML
// fragments and relationships the model does not represent into `wb.preserved` /
// `ws.preserved` (shapes in ../common/preserved.ts). Reader-only: the writer side
// (../write/preserve.ts) just re-emits what is captured here.
//
// Ownership rules (what is NOT preserved because the model owns it):
// - parts: workbook, styles, shared strings, worksheets (incl. ones filtered out by
//   opts.sheets), docProps core/app, calcChain (dropped on purpose: Excel rebuilds it and a
//   stale one triggers repair prompts), content types and .rels;
// - worksheet elements parsed by the core or claimed by a feature reader (the attributes of
//   those elements are scanned for r:id so the relationships they use are not kept twice);
// - drawings: pictures become ws.images; every other anchor (charts, shapes, groups, linked
//   pictures, mc:AlternateContent) is kept raw and merged back into the drawing the images
//   writer emits;
// - styles.xml: named cell styles (cellStyleXfs / cellStyles) are kept raw, their font / fill /
//   border ids remapped to the registry; cellXfs keep their xfId (StylesHandler.apply);
// - legacy VML: a VML part holding only note shapes is regenerated by the comments feature;
//   when the sheet has notes and other shapes (form controls), the other shapes are kept
//   (`ws.preserved.vml`) and merged into the VML the comments feature writes; a VML without
//   notes is kept together with its <legacyDrawing>;
// - `comments` relationships when the comments feature modelled the sheet's notes (it
//   regenerates them) and `threadedComment` / `person` ones when it modelled the threads;
//   pivotTables, queryTables, slicers, ... (relationships
//   no element references) are kept.
//
// Which features are enabled is the caller's choice (`ReadOptions.features`; `./lite` enables
// none by default): whatever a disabled feature would have modelled is simply not claimed and
// falls through to the rules above, so it round-trips raw. Kept XML that refers to styles.xml
// differential formats (cfRule / table / pivot `*dxfId`) is remapped to the registry's dxf
// indices (the reader interns, and so may merge, the file's dxfs).

