const NS_R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships';
/** Namespaces declared on the root of the parts the writer generates (fragments skip them). */
const OUT_SHEET: Scope = new Map([
  ['', 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'],
  ['r', NS_R],
]);
const OUT_STYLES: Scope = new Map([
  ['', 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'],
]);
const OUT_DRAWING: Scope = new Map([
  ['xdr', 'http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing'],
  ['a', 'http://schemas.openxmlformats.org/drawingml/2006/main'],
  ['r', NS_R],
]);
const RELS_NS = /officeDocument\/(2006\/)?relationships$/;

type Scope = ReadonlyMap<string, string>;
/** Attribute rewrite: return the (escaped) value to write, or undefined for the default. */
type AttrMap = (key: string, value: string, relNs: boolean) => string | undefined;

function scopeOf(a: XmlAttrs, into = new Map<string, string>()): Map<string, string> {
  for (const k in a) {
    if (k === 'xmlns') into.set('', a[k]!);
    else if (k.startsWith('xmlns:')) into.set(k.slice(6), a[k]!);
  }
  return into;
}

/** Raw attributes (leading space), skipping namespace declarations and `skip`. */
function rawAttrs(a: XmlAttrs, skip?: string): string {
  let s = '';
  for (const k in a) {
    if (k === skip || k === 'xmlns' || k.startsWith('xmlns:')) continue;
    s += ` ${k}="${escapeAttr(a[k]!)}"`;
  }
  return s;
}

/**
 * Re-serializes a subtree from tokenizer events (prefixes kept). On `end()` the root element
 * gets the namespace declarations it needs from the enclosing scope, so the fragment is
 * self-contained wherever it is pasted.
 */
export class RawXml implements RawHandler {
  private s = '';
  private rootAt = -1;
  private sc = false;
  private readonly used = new Set<string>();
  private readonly local = new Map<string, string>();
  private readonly scope: Scope;
  private readonly map: AttrMap | undefined;
  private readonly out: Scope;
  result = '';
  onEnd: ((xml: string) => void) | undefined;

  constructor(scope: Scope, map: AttrMap | undefined, out: Scope) {
    this.scope = scope;
    this.map = map;
    this.out = out;
  }

  private uri(p: string): string | undefined {
    return this.local.get(p) ?? this.scope.get(p);
  }

  open(name: string, a: XmlAttrs, selfClosing: boolean): void {
    const i = name.indexOf(':');
    if (i > 0) this.used.add(name.slice(0, i));
    let t = `<${name}`;
    if (this.rootAt < 0) this.rootAt = t.length;
    for (const k in a) {
      const v = a[k]!;
      if (k === 'xmlns' || k.startsWith('xmlns:')) {
        this.local.set(k.slice(6), v);
        t += ` ${k}="${escapeAttr(v)}"`;
        continue;
      }
      const j = k.indexOf(':');
      const p = j > 0 ? k.slice(0, j) : '';
      if (p) this.used.add(p);
      // prefixes named in mc:Ignorable / mc:Choice Requires must stay declared
      if (k.endsWith('Ignorable') || k === 'Requires')
        for (const x of v.split(/\s+/)) if (x) this.used.add(x);
      const out = this.map?.(k, v, p !== '' && RELS_NS.test(this.uri(p) ?? ''));
      t += ` ${k}="${out ?? escapeAttr(v)}"`;
    }
    this.s += selfClosing ? `${t}/>` : `${t}>`;
    this.sc = selfClosing;
  }

  close(name: string): void {
    if (this.sc) this.sc = false;
    else this.s += `</${name}>`;
  }

  text(t: string): void {
    this.s += escapeText(t);
  }

  end(): void {
    let decl = '';
    const def = this.scope.get('');
    if (!this.local.has('') && def !== undefined && def !== this.out.get('')) {
      decl += ` xmlns="${escapeAttr(def)}"`;
    }
    for (const p of this.used) {
      if (p === 'xml' || p === 'xmlns' || this.local.has(p)) continue;
      const u = this.scope.get(p);
      if (u !== undefined && u !== this.out.get(p)) decl += ` xmlns:${p}="${escapeAttr(u)}"`;
    }
    this.result = this.s.slice(0, this.rootAt) + decl + this.s.slice(this.rootAt);
    this.onEnd?.(this.result);
  }
}

/** Placeholder for relationship id `id` (resolved by `compact`). */
const ph = (id: string): string => `\x01${escapeAttr(id)}\x01`;
/** Id placeholders. */
// biome-ignore lint/suspicious/noControlCharactersInRegex: U+0001 delimits placeholders
const PH_ID = /\x01([^\x01]*)\x01/g;
// biome-ignore lint/suspicious/noControlCharactersInRegex: U+0001 delimits placeholders
const PH_ONE = /\x01([^\x01]*)\x01/;

/** Map relationship-namespace attributes to id placeholders when the id is known. */
function relMap(rels: ReadonlyMap<string, Relationship> | undefined): AttrMap {
  return (_k, v, relNs) => (relNs && rels?.has(v) ? ph(v) : undefined);
}

const SHEETISH = /\/(worksheet|chartsheet|dialogsheet|macrosheet|xlMacrosheet|xlIntlMacrosheet)$/;
// FeaturePropertyBag: in-cell checkboxes, regenerated from Style.checkbox
const BOOK_OWNED = /\/(styles|sharedStrings|calcChain|FeaturePropertyBag)$/;

/** `dxfId`-like attributes (cfRule dxfId, table headerRowDxfId / dataDxfId / ..., pivot formats). */
const DXF_ATTR = /(\s[\w:]*[dD]xfId)="(\d+)"/g;
/** Parts whose XML refers to styles.xml dxfs. */
const DXF_PART = /\.(table|pivotTable)\+xml$/;

export class Preserver {
  private readonly memo = new Map<string, PPart | null>();
  private readonly files: Map<string, LazyEntry>;
  private readonly pkg: XlsxPackage;
  /** Lower-case paths owned by the model (never preserved). */
  private readonly owned: Set<string>;
  /** File dxf index → registry dxf index; undefined when it is the identity. */
  private readonly dxf: Uint32Array | undefined;
  /** Part-family numbers taken by kept content outside kept parts (merged VML shapes). */
  private readonly reserve: string[] = [];

  constructor(
    files: Map<string, LazyEntry>,
    pkg: XlsxPackage,
    owned: Iterable<string>,
    dxfMap?: Uint32Array,
  ) {
    this.files = files;
    this.pkg = pkg;
    this.owned = new Set();
    for (const p of owned) this.owned.add(p.toLowerCase());
    this.dxf = dxfMap?.some((v, i) => v !== i) ? dxfMap : undefined;
  }

  private text(path: string): string | undefined {
    const e = this.files.get(this.pkg.entry(path));
    return e && decodePart(e.bytes());
  }

  /** Preserved part for a zip path (memoized; recursively follows its relationships). */
  part(path: string): PPart | undefined {
    const key = path.toLowerCase();
    const hit = this.memo.get(key);
    if (hit !== undefined) return hit ?? undefined;
    const name = this.pkg.entry(path);
    const e = this.files.get(name);
    if (!e || this.owned.has(key) || key.endsWith('.rels') || key === '[content_types].xml') {
      this.memo.set(key, null);
      return undefined;
    }
    let ct: string | undefined;
    let def: string | undefined;
    const types = this.pkg.ct;
    if (types) {
      for (const [k, v] of types.overrides) if (k.toLowerCase() === key) ct = v;
      if (ct === undefined) def = types.defaults.get(key.slice(key.lastIndexOf('.') + 1));
    }
    const rels: POwnRel[] = [];
    const dxf = this.dxf;
    const data =
      dxf && ct && DXF_PART.test(ct)
        ? (): Uint8Array => {
            const x = decodePart(e.bytes());
            return new TextEncoder().encode(
              x.replace(DXF_ATTR, (_, k: string, v: string) => `${k}="${dxf[+v] ?? 0}"`),
            );
          }
        : () => e.bytes();
    const p: PPart = { path: name, ct, def, data, rels };
    this.memo.set(key, p);
    for (const r of this.pkg.relsOf(name)?.values() ?? []) {
      const t = this.target(r);
      if (t !== undefined) rels.push({ id: r.id, type: r.type, target: t });
    }
    return p;
  }

  private target(r: Relationship): PPart | string | undefined {
    return r.external ? r.target : this.part(r.path);
  }

  /**
   * Resolve placeholders "\x01<rId>\x01" of fragments against `rels` into "\x01<k>\x01"
   * indices of a fresh PRel list (unresolvable ids are written back verbatim).
   */
  private compact(
    xmls: string[],
    rels: ReadonlyMap<string, Relationship> | undefined,
    out: PRel[],
    index: Map<string, number>,
  ): string[] {
    return xmls.map((x) =>
      x.replace(PH_ID, (_, id: string) => {
        const raw = id
          .replace(/&quot;/g, '"')
          .replace(/&lt;/g, '<')
          .replace(/&amp;/g, '&');
        let k = index.get(raw);
        if (k === undefined) {
          const r = rels?.get(raw);
          const t = r && this.target(r);
          if (t === undefined) return id;
          k = out.push({ type: r!.type, target: t }) - 1;
          index.set(raw, k);
        }
        return `\x01${k}\x01`;
      }),
    );
  }

  // ---------------------------------------------------------------- worksheets

  /** Capture hooks for one worksheet; call `finish` after its features finished. */
  sheet(rels: ReadonlyMap<string, Relationship> | undefined): SheetCap {
    return new SheetCap(rels, this.dxf);
  }

  /** @internal Build ws.preserved from a finished capture. */
  finishSheet(c: SheetCap, ws: Worksheet, sheetId: number): void {
    const rels = c.rels;
    const frags: [number, number, string][] = [];
    let vmlKept: PVml | undefined;
    for (const f of c.frags) {
      if (f[0] === SheetSlot.legacyDrawing && ws.comments !== undefined) {
        // notes-only VML: regenerated by the comments feature
        const m = PH_ONE.exec(f[2]);
        const r = m && rels?.get(m[1]!);
        const vml = r && !r.external ? this.text(r.path) : undefined;
        if (vml === undefined || !/ObjectType="(?!Note")/.test(vml)) continue;
        // notes + other shapes (form controls, ...): the comments feature regenerates the notes
        // and merges the other shapes into its VML (not possible when they link parts)
        if (!this.pkg.relsOf(r!.path)?.size) {
          vmlKept = vmlShapes(vml);
          if (vmlKept) {
            for (const b of vmlKept.blocks) this.reserve.push(`vmlShapeBlock${b}`);
            continue;
          }
        }
      }
      frags.push(f);
    }
    const out: PRel[] = [];
    const index = new Map<string, number>();
    const xmls = this.compact(
      frags.map((f) => f[2]),
      rels,
      out,
      index,
    );
    const lx = this.compact(
      c.links.map((l) => l[2]),
      rels,
      out,
      index,
    );
    const links: PLink[] = c.links.map((l, i) => ({ ref: l[0], formula: l[1], xml: lx[i]! }));
    const implicit: number[] = [];
    for (const r of rels?.values() ?? []) {
      if (c.refs.has(r.id) || c.seen.has(r.id)) continue;
      // notes modelled by the comments feature are regenerated; otherwise kept raw
      if (ws.comments !== undefined && relTypeIs(r.type, 'comments')) continue;
      // threads modelled by the comments feature are regenerated too
      if (ws.threadedComments !== undefined && /\/threadedComment$/.test(r.type)) continue;
      const t = this.target(r);
      if (t === undefined) continue;
      implicit.push(out.push({ type: r.type, target: t }) - 1);
    }
    const tables: PTable[] = [];
    for (const r of rels?.values() ?? []) {
      // modelled tables whose part has relationships (query tables): keep the part
      if (r.external || !relTypeIs(r.type, 'table') || !c.refs.has(r.id)) continue;
      if (!this.pkg.relsOf(r.path)?.size) continue;
      const head = /<(?:\w+:)?table\b[^>]*>/.exec(this.text(r.path) ?? '')?.[0] ?? '';
      const name = / name="([^"]*)"/.exec(head)?.[1];
      const t = ws.tables?.find((x) => x.name === name);
      const p = t && this.part(r.path);
      if (p) {
        tables.push({
          table: t,
          key: JSON.stringify(t),
          rel: { type: r.type, target: p },
          id: +(/ id="(\d+)"/.exec(head)?.[1] ?? 0),
        });
      }
    }
    let drawing: PDrawing | undefined;
    for (const r of rels?.values() ?? []) {
      if (!r.external && relTypeIs(r.type, 'drawing') && c.refs.has(r.id)) {
        drawing = this.drawing(r.path);
        break;
      }
    }
    const empty =
      frags.length === 0 &&
      implicit.length === 0 &&
      !drawing &&
      !vmlKept &&
      tables.length === 0 &&
      links.length === 0 &&
      c.prAttrs === '';
    if (empty && sheetId === ws.id) return;
    const pf: PFrag[] = frags.map((f, i) => ({
      slot: f[0],
      order: f[1],
      xml: xmls[i]!,
      linked: xmls[i]!.includes('\x01'),
    }));
    const ps: PSheet = {
      name: ws.name,
      sheetId,
      frags: pf,
      rels: out,
      implicit,
      prAttrs: c.prAttrs,
      drawing,
      vml: vmlKept,
      tables: tables.length ? tables : undefined,
      links: links.length ? links : undefined,
      w: presWrite,
    };
    ws.preserved = ps;
  }

  /** Anchors of a drawing part that are not modelled pictures (see images reader). */
  private drawing(path: string): PDrawing | undefined {
    const xml = this.text(path);
    if (xml === undefined) return undefined;
    const drels = this.pkg.relsOf(path);
    const kept: string[] = [];
    let scope: Map<string, string> | undefined;
    let raw: RawXml | undefined;
    let depth = 0;
    let pic = false;
    let maxId = 0;
    let curMax = 0;
    try {
      parseXml(xml, {
        open(name, a, sc) {
          depth++;
          if (depth === 1) {
            scope = scopeOf(a);
            return;
          }
          if (depth === 2) {
            raw = new RawXml(scope!, relMap(drels), OUT_DRAWING);
            pic = false;
            curMax = 0;
          }
          const ln = localName(name);
          if (depth === 3 && ln === 'pic') pic = true;
          if (ln === 'blip' && pic) {
            for (const k in a) {
              if (k.endsWith(':embed')) {
                const r = drels?.get(a[k]!);
                if (!r || r.external)
                  pic = false; // not modelled: keep raw
                else pic = true;
              }
            }
          }
          if (ln === 'cNvPr' && a.id !== undefined && +a.id > curMax) curMax = +a.id;
          raw?.open(name, a, sc);
        },
        text(t) {
          raw?.text(t);
        },
        close(name) {
          if (depth >= 2) raw?.close(name);
          if (depth === 2 && raw) {
            raw.end();
            // modelled pictures (direct pic with an embedded blip) are re-emitted by images
            if (!(pic && /:embed=/.test(raw.result))) {
              kept.push(raw.result);
              if (curMax > maxId) maxId = curMax;
            }
            raw = undefined;
          }
          depth--;
        },
      });
    } catch {
      return undefined;
    }
    if (kept.length === 0) return undefined;
    const rels: PRel[] = [];
    const out = this.compact(kept, drels, rels, new Map());
    return { xml: out.join(''), rels, maxId };
  }

  // ---------------------------------------------------------------- workbook

  /** Build wb.preserved (call after every sheet). */
  book(
    wb: Workbook,
    wbPath: string,
    wbXml: string | undefined,
    entries: readonly SheetEntry[],
    filter: Set<string> | undefined,
    stylesXml: string | undefined,
    dxfMap: Uint32Array | undefined,
    named: IdMaps | undefined,
    sheetMap: ReadonlyMap<number, number>,
  ): void {
    const rels = this.pkg.relsOf(wbPath);
    const frags: [number, number, string][] = [];
    let prAttrs = '';
    let calcAttrs: string | undefined;
    const seen = new Set<string>();
    if (wbXml !== undefined) {
      let scope: Map<string, string> | undefined;
      let depth = 0;
      let raw: RawXml | undefined;
      let slot = 0;
      parseXml(wbXml, {
        open(name, a, sc) {
          depth++;
          if (depth === 1) scope = scopeOf(a);
          else if (raw) raw.open(name, a, sc);
          else if (depth === 2) {
            const ln = localName(name);
            if (ln === 'workbookPr') prAttrs = rawAttrs(a, 'date1904');
            else if (ln === 'calcPr') calcAttrs = rawAttrs(a, 'fullCalcOnLoad');
            else if (ln === 'sheets') {
              for (const e of entries) if (e.rId) seen.add(e.rId);
            } else if (ln !== 'bookViews' && ln !== 'definedNames') {
              const s = (BookSlot as Record<string, number>)[ln];
              if (s !== undefined) {
                slot = s;
                raw = new RawXml(scope!, relMap(rels), OUT_SHEET);
                raw.open(name, a, sc);
              }
            }
          }
        },
        text(t) {
          raw?.text(t);
        },
        close(name) {
          if (raw) {
            raw.close(name);
            if (depth === 2) {
              raw.end();
              frags.push([slot, 0, raw.result]);
              raw = undefined;
            }
          }
          depth--;
        },
      });
    }
    const out: PRel[] = [];
    const index = new Map<string, number>();
    const xmls = this.compact(
      frags.map((f) => f[2]),
      rels,
      out,
      index,
    );
    const names = new Set(wb.worksheets.map((w) => w.name.toLowerCase()));
    const sheets: PForeignSheet[] = [];
    /** The loaded worksheet of file sheet index j. */
    const wsAt = (j: number): Worksheet | undefined => {
      const k = sheetMap.get(j);
      return k === undefined ? undefined : wb.worksheets[k];
    };
    for (let i = 0; i < entries.length; i++) {
      const e = entries[i]!;
      const r = e.rId !== undefined ? rels?.get(e.rId) : undefined;
      if (!r || r.external || relTypeIs(r.type, 'worksheet') || !SHEETISH.test(r.type)) continue;
      const lower = e.name.toLowerCase();
      if ((filter && !filter.has(lower)) || names.has(lower)) continue;
      const p = this.part(r.path);
      if (!p) continue;
      // the selected tab is chosen by the writer: drop tabSelected from the kept sheet view
      const data = p.data;
      (p as { data: () => Uint8Array }).data = () =>
        new TextEncoder().encode(decodePart(data()).replace(/ tabSelected="(1|true)"/g, ''));
      let prev: Worksheet | undefined;
      let next: Worksheet | undefined;
      for (let j = i - 1; j >= 0 && !prev; j--) prev = wsAt(j);
      for (let j = i + 1; j < entries.length && !next; j++) next = wsAt(j);
      sheets.push({
        name: e.name,
        sheetId: e.sheetId,
        state: e.state,
        rel: { type: r.type, target: p },
        prev,
        next,
      });
    }
    const implicit: number[] = [];
    let vba = false;
    for (const r of rels?.values() ?? []) {
      if (relTypeIs(r.type, 'vbaProject')) vba = true;
      if (seen.has(r.id) || index.has(r.id) || SHEETISH.test(r.type) || BOOK_OWNED.test(r.type))
        continue;
      // persons read by the comments feature are written from wb.persons
      if (wb.persons !== undefined && /\/person$/.test(r.type)) continue;
      const t = this.target(r);
      if (t !== undefined) implicit.push(out.push({ type: r.type, target: t }) - 1);
    }
    const root: PRel[] = [];
    for (const r of this.pkg.relsOf('')?.values() ?? []) {
      if (/\/(officeDocument|core-properties|extended-properties|origin|signature)$/.test(r.type))
        continue;
      const t = this.target(r);
      if (t !== undefined) root.push({ type: r.type, target: t });
    }
    const mainCt = this.pkg.ct?.overrides.get(wbPath);
    const st = stylesXml !== undefined ? styles(stylesXml, dxfMap, named) : undefined;
    const reserve = this.reserve;
    for (const p of this.memo.values()) {
      if (!p || !/\.vml$/i.test(p.path)) continue;
      const m = /idmap[^>]*\sdata="([\d,\s]+)"/.exec(decodePart(p.data()));
      if (m) for (const n of m[1]!.split(',')) if (n.trim()) reserve.push(`vmlShapeBlock${+n}`);
    }
    const pb: PBook = {
      frags: frags.map((f, i) => ({
        slot: f[0],
        order: 0,
        xml: xmls[i]!,
        linked: xmls[i]!.includes('\x01'),
      })),
      rels: out,
      implicit,
      root,
      sheets,
      prAttrs,
      calcAttrs,
      mainCt: vba && mainCt && /macroEnabled/i.test(mainCt) ? mainCt : undefined,
      tableStyles: st?.[0],
      stylesTail: st?.[1] ?? '',
      named: st?.[2],
      reserve,
      w: presWrite,
    };
    wb.preserved = pb;
  }
}

const OUT_VML: Scope = new Map([
  ['v', 'urn:schemas-microsoft-com:vml'],
  ['o', 'urn:schemas-microsoft-com:office:office'],
  ['x', 'urn:schemas-microsoft-com:office:excel'],
]);

/**
 * The non-note shapes of a legacy VML part (+ the shape types they may use, except the note
 * type the comments feature declares) and its shape-id blocks (`o:idmap`); undefined when the
 * part cannot be parsed or holds no such shape.
 */
function vmlShapes(xml: string): PVml | undefined {
  const kept: string[] = [];
  /** idmap blocks of the part / blocks of the kept shapes' ids. */
  const all: number[] = [];
  const blocks = new Set<number>();
  let block = -1;
  let scope: Map<string, string> | undefined;
  let raw: RawXml | undefined;
  let depth = 0;
  let keep = false;
  let shapes = 0;
  try {
    parseXml(xml, {
      open(name, a, sc) {
        depth++;
        const ln = localName(name);
        if (depth === 1) scope = scopeOf(a);
        else if (depth === 2 && ln !== 'shapelayout') {
          raw = new RawXml(scope!, undefined, OUT_VML);
          keep = ln !== 'shapetype' || a.id !== '_x0000_t202';
          const m = ln !== 'shapetype' && /(\d+)$/.exec(a['o:spid'] ?? a.id ?? '');
          block = m ? Math.floor(+m[1]! / 1024) : -1;
        }
        if (ln === 'idmap') {
          for (const n of (a.data ?? '').split(',')) if (n.trim()) all.push(+n);
        } else if (ln === 'ClientData' && a.ObjectType === 'Note') keep = false;
        raw?.open(name, a, sc);
      },
      text(t) {
        raw?.text(t);
      },
      close(name) {
        raw?.close(name);
        if (depth === 2 && raw) {
          raw.end();
          if (keep) {
            kept.push(raw.result);
            if (localName(name) !== 'shapetype') shapes++;
            if (block >= 0) blocks.add(block);
          }
          raw = undefined;
        }
        depth--;
      },
    });
  } catch {
    return undefined;
  }
  // only the blocks the kept shapes use (the notes' blocks are allocated anew)
  return shapes ? { xml: kept.join(''), blocks: blocks.size ? [...blocks] : all } : undefined;
}

/** File font / fill / border index → registry index (StylesHandler after `apply`). */
interface IdMaps {
  readonly fontMap: readonly number[];
  readonly fillMap: readonly number[];
  readonly borderMap: readonly number[];
}

const NAMED_ID: Record<string, keyof IdMaps> = {
  fontId: 'fontMap',
  fillId: 'fillMap',
  borderId: 'borderMap',
};

/**
 * styles.xml pieces the model drops: tableStyles (dxfIds remapped), colors, extLst and, with
 * `named`, the named cell styles (cellStyleXfs with font / fill / border ids remapped, cellStyles).
 */
function styles(
  xml: string,
  dxfMap: Uint32Array | undefined,
  named: IdMaps | undefined,
): [string | undefined, string, [string, string] | undefined] {
  let table: string | undefined;
  let colors = '';
  let ext = '';
  let styleXfs: string | undefined;
  let cellStyles =
    '<cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles>';
  let scope: Map<string, string> | undefined;
  let depth = 0;
  let raw: RawXml | undefined;
  let ln = '';
  const dxf: AttrMap = (k, v) => (k === 'dxfId' && dxfMap ? String(dxfMap[+v] ?? 0) : undefined);
  const ids: AttrMap = (k, v) => {
    const m = NAMED_ID[k];
    return m ? String(named![m][+v] ?? 0) : undefined;
  };
  try {
    parseXml(xml, {
      open(name, a, sc) {
        depth++;
        if (depth === 1) scope = scopeOf(a);
        else if (raw) raw.open(name, a, sc);
        else if (depth === 2) {
          ln = localName(name);
          if (
            ln === 'tableStyles' ||
            ln === 'colors' ||
            ln === 'extLst' ||
            (named && (ln === 'cellStyleXfs' || ln === 'cellStyles'))
          ) {
            raw = new RawXml(
              scope!,
              ln === 'tableStyles' ? dxf : ln === 'cellStyleXfs' ? ids : undefined,
              OUT_STYLES,
            );
            raw.open(name, a, sc);
          }
        }
      },
      text(t) {
        raw?.text(t);
      },
      close(name) {
        if (raw) {
          raw.close(name);
          if (depth === 2) {
            raw.end();
            if (ln === 'tableStyles') table = raw.result;
            else if (ln === 'colors') colors = raw.result;
            else if (ln === 'cellStyleXfs') styleXfs = raw.result;
            else if (ln === 'cellStyles') cellStyles = raw.result;
            else ext = raw.result;
            raw = undefined;
          }
        }
        depth--;
      },
    });
  } catch {
    return [undefined, '', undefined];
  }
  return [table, colors + ext, styleXfs !== undefined ? [styleXfs, cellStyles] : undefined];
}

/** `<sheetFormatPr>` attributes modelled by ws.properties (or derived from it). */
const FORMAT_PR = [
  'defaultRowHeight',
  'defaultColWidth',
  'customHeight',
  'outlineLevelRow',
  'outlineLevelCol',
];

/** Per-sheet capture state (SheetCapture for the sheet parser). */
export class SheetCap implements SheetCapture {
  readonly frags: [number, number, string][] = [];
  /** Relationship ids referenced by consumed elements. */
  readonly refs: Set<string> = new Set();
  /** Relationship ids referenced by captured fragments. */
  readonly seen: Set<string> = new Set();
  prAttrs = '';
  private scope: Map<string, string> = new Map();
  readonly rels: ReadonlyMap<string, Relationship> | undefined;
  private readonly dxf: Uint32Array | undefined;

  constructor(rels: ReadonlyMap<string, Relationship> | undefined, dxf?: Uint32Array) {
    this.rels = rels;
    this.dxf = dxf;
  }

  root(a: XmlAttrs): void {
    this.scope = scopeOf(a);
  }

  sheetPr(a: XmlAttrs): void {
    this.prAttrs = rawAttrs(a);
  }

  formatPr(a: XmlAttrs): void {
    // attributes ws.properties does not model (zeroHeight, thickTop, baseColWidth, ...);
    // customHeight follows defaultRowHeight; other extension attributes are dropped
    let s = '';
    for (const k in a) {
      if (k.includes(':') || k === 'xmlns' || FORMAT_PR.includes(k)) continue;
      s += ` ${k}="${escapeAttr(a[k]!)}"`;
    }
    if (s) this.frags.push([SheetSlot.sheetFormatPr, 9, `<sheetFormatPr${s}/>`]);
  }

  ref(a: XmlAttrs): void {
    for (const k in a) if (k.endsWith(':id')) this.refs.add(a[k]!);
  }

  /** Formula-cell hyperlinks: [ref, formula, xml with placeholders]. */
  readonly links: [string, unknown, string][] = [];

  formulaLink(ref: string, formula: unknown, h: HyperlinkAttrs): void {
    const id = h.rId !== undefined && this.rels?.has(h.rId) ? ` r:id="${ph(h.rId)}"` : '';
    let x = `<hyperlink ref="${ref}"${id}`;
    if (h.location !== undefined) x += ` location="${escapeAttr(h.location)}"`;
    if (h.tooltip !== undefined) x += ` tooltip="${escapeAttr(h.tooltip)}"`;
    if (h.display !== undefined) x += ` display="${escapeAttr(h.display)}"`;
    if (id || h.location !== undefined) this.links.push([ref, formula, `${x}/>`]);
  }

  start(path: string, name: string, _a: XmlAttrs, _sc: boolean): RawHandler {
    const rels = this.rels;
    const seen = this.seen;
    const dxf = this.dxf;
    const raw = new RawXml(
      this.scope,
      (k, v, relNs) => {
        if (dxf && k === 'dxfId') return String(dxf[+v] ?? 0);
        if (!relNs || !rels?.has(v)) return undefined;
        seen.add(v);
        return ph(v);
      },
      OUT_SHEET,
    );
    const ln = localName(name);
    const slot =
      path.startsWith('sheetPr/') || path.startsWith('extLst/')
        ? path.charCodeAt(0) === 115
          ? SheetSlot.sheetPr
          : SheetSlot.extLst
        : (SheetSlot as Record<string, number>)[ln];
    const order = (SheetPrOrder as Record<string, number>)[ln] ?? 9;
    raw.onEnd = (xml) => {
      // Excel wraps x14 elements (controls, oleObjects) in mc:AlternateContent: the slot is the
      // one of the first element of the first choice
      const k =
        slot ??
        (SheetSlot as Record<string, number>)[
          /<[\w:]*?Choice\b[^>]*>\s*<(?:\w+:)?(\w+)/.exec(xml)?.[1] ?? ''
        ];
      if (k !== undefined && k !== SheetSlot.sheetData) this.frags.push([k, order, xml]);
    };
    return raw;
  }
}
